/** Seed indices are hand-written and always in range; `noUncheckedIndexedAccess` needs the narrowing. */
function at<T>(list: T[], i: number): T {
  const item = list[i];
  if (item === undefined) throw new Error(`safety mock: index ${i} out of range`);
  return item;
}

