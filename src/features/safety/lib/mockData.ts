// Fallback rows for the Safety page while `GET /safety/events` / `GET /safety/scorecard` return
// nothing (empty list or request failure). `SafetyPage` swaps these in only when the API gave it
// zero rows, so real data always wins. Rows are pre-joined (`driver`/`vehicle` filled in) so the
// page does not depend on `/drivers` or `/vehicles` either.
//
